export function getNodeDefinition(type: NodeType): NodeDefinition | undefined {
  return NODE_REGISTRY.find((node) => node.type === type);
}

export function getNodesByCategory(category: string): NodeDefinition[] {
  return NODE_REGISTRY.filter((node) => node.category === category && !node.hidden);
}

export function getCategories(): string[] {
  return [...new Set(NODE_REGISTRY.filter((node) => !node.hidden).map((node) => node.category))];
}
